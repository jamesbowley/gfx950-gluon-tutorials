"""results/modes.md from results/trace.jsonl, pmc.jsonl, release.jsonl and clocks.jsonl."""

import json
import os
import statistics

import modes as M

LABEL = {"13": "v13", "20:STREAMK_POLICY=capped": "capped", "20:STREAMK_POLICY=two_tile": "two-tile"}
SMALL = M.SHAPES[:6]
BIG = M.SHAPES[6:]
OLD = os.path.join(M.REPO, "experiments", "streamk_capped_vs_auto", "results", "between_launches_raw.md")
OLD_MODES = {"nothing": "nothing", "zero 256 MB (do_bench)": "dirty_cold", "read 256 MB": "clean_cold",
             "zero 64 MB": "zero64", "sleep 100 us": "sleep"}
OLD_LABEL = {"v13": "13", "v20 policy=capped": "20:STREAMK_POLICY=capped",
             "v20 policy=two_tile": "20:STREAMK_POLICY=two_tile"}
# (name, base mode, changed mode): each changes one thing.
FACTORS = [
    ("dirty, cold inputs", "clean_cold", "dirty_cold"),
    ("dirty, warm inputs", "clean_warm", "dirty_warm"),
    ("warm, clean caches", "clean_cold", "clean_warm"),
    ("warm, dirty caches", "dirty_cold", "dirty_warm"),
    ("idle gap, clean cold", "clean_cold", "clean_cold_idle"),
    ("idle gap, clean warm", "clean_warm", "clean_warm_idle"),
    ("idle gap, dirty cold", "dirty_cold", "dirty_cold_idle"),
    ("idle gap, dirty warm", "dirty_warm", "dirty_warm_idle"),
    ("busy gap instead of idle, clean warm", "clean_warm_idle", "clean_warm_busy"),
    ("previous GEMM back to back instead of idle", "sleep", "nothing"),
    ("A written by a predecessor, B cold", "clean_cold", "write_a"),
]


def load(name):
    path = os.path.join(M.RESULTS, name)
    if not os.path.exists(path):
        return []
    return [json.loads(line) for line in open(path)]


def pct(a, b):
    return 100 * (a / b - 1)


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + \
           ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]


def old_events():
    """{(shape, version, mode): us} from between_launches.py's CUDA-event table."""
    if not os.path.exists(OLD):
        return {}
    lines = [l for l in open(OLD) if l.startswith("| ")]
    head = [c.strip() for c in lines[0].strip().strip("|").split("|")]
    out = {}
    for l in lines[1:]:
        c = [x.strip() for x in l.strip().strip("|").split("|")]
        if c[0] == "shape" or c[1] not in OLD_LABEL:
            continue
        for h, x in zip(head[2:], c[2:]):
            out[(c[0], OLD_LABEL[c[1]], OLD_MODES[h])] = float(x)
    return out


def main():
    tr = {(r["shape"], r["version"], r["mode"]): r for r in load("trace.jsonl")}
    shapes = [s for s in M.SHAPES if any(k[0] == s for k in tr)]
    L = ["# GEMM time by the work between launches (kernel-only)", "",
         "Generated by `modes.py report`. Kernel times are rocprofv3 dispatch durations, median of 100 launches "
         "after 10 warm-up launches, every (version, mode) in one process per shape. Modes are described in "
         "`modes.py`.", ""]

    # 1. Kernel-only against CUDA events.
    ev = old_events()
    rows = []
    for s in shapes:
        for v in M.VERSIONS:
            cells = []
            for m in ("nothing", "zero64", "clean_cold", "dirty_cold", "sleep"):
                k, e = tr.get((s, v, m)), ev.get((s, v, m))
                cells.append("-" if not k else f"{k['us']:.1f}" + (f" ({e:.1f})" if e else ""))
            rows.append([s, LABEL[v]] + cells)
    L += ["## 1. Kernel-only against CUDA events", "",
          "Kernel-only time in us, with between_launches.py's CUDA-event time in brackets for the same mode "
          "(from experiments/streamk_capped_vs_auto). zero 256 MB is `dirty_cold`, read 256 MB `clean_cold`.", ""]
    L += table(["shape", "version", "nothing", "zero 64 MB", "read 256 MB", "zero 256 MB", "sleep"], rows)

    # 2. Every mode.
    L += ["", "## 2. Kernel time in every mode (us)", "",
          "\"gap\" is the median idle time before the GEMM, \"before\" the median length of the kernel just "
          "before it, for the two-tile rows.", ""]
    rows = []
    for s in shapes:
        for v in M.VERSIONS:
            rows.append([s, LABEL[v]] + [f"{tr[(s, v, m)]['us']:.1f}" if (s, v, m) in tr else "-" for m in M.MODES])
        tt = "20:STREAMK_POLICY=two_tile"
        rows.append([s, "gap / before"] + [f"{tr[(s, tt, m)]['gap']:.0f} / {tr[(s, tt, m)]['prev_us']:.0f}"
                                           if (s, tt, m) in tr else "-" for m in M.MODES])
    L += table(["shape", "version"] + M.MODES, rows)

    # 3. Two-tile against capped.
    cap, tt = "20:STREAMK_POLICY=capped", "20:STREAMK_POLICY=two_tile"
    L += ["", "## 3. Two-tile against capped", "",
          "Positive means two-tile is faster (capped time / two-tile time - 1).", ""]
    rows = []
    for s in shapes:
        rows.append([s] + [f"{pct(tr[(s, cap, m)]['us'], tr[(s, tt, m)]['us']):+.1f}%"
                           if (s, cap, m) in tr and (s, tt, m) in tr else "-" for m in M.MODES])
    for name, group in (("median, 6 small shapes", SMALL), ("median, 2 big shapes", BIG)):
        g = [s for s in group if s in shapes]
        if g:
            rows.append([f"**{name}**"] + [f"{statistics.median(pct(tr[(s, cap, m)]['us'], tr[(s, tt, m)]['us']) for s in g):+.1f}%"
                                         for m in M.MODES])
    L += table(["shape"] + M.MODES, rows)

    # 4. Factor effects.
    L += ["", "## 4. One factor at a time", "",
          "Change in kernel time when one thing changes (positive: slower), median over the 6 small shapes, "
          "with the range in brackets. v13 is data-parallel.", ""]
    rows = []
    for name, base, new in FACTORS:
        cells = []
        for v in M.VERSIONS:
            xs = [pct(tr[(s, v, new)]["us"], tr[(s, v, base)]["us"]) for s in SMALL
                  if (s, v, new) in tr and (s, v, base) in tr]
            cells.append(f"{statistics.median(xs):+.1f}% ({min(xs):+.1f} to {max(xs):+.1f})" if xs else "-")
        rows.append([name, f"{base} -> {new}"] + cells)
    L += table(["factor", "modes", "v13", "capped", "two-tile"], rows)

    # 5. Counters.
    pm = {(r["shape"], r["version"], r["mode"]): r for r in load("pmc.jsonl")}
    if pm:
        L += ["", "## 5. Counters", "",
              "Per GEMM dispatch, median of 10 counted launches (rocprofv3 --pmc, which serialises dispatches). "
              "L2 reads / writes are TCC_EA0_RDREQ / WRREQ (requests from L2 to memory), DRAM the subset sent to "
              "DRAM; op write-backs are TCC_ALL_TC_OP_WB_WRITEBACK (lines written back by cache operations such "
              "as the release's buffer_wbl2), normal write-backs are evictions. Stalls are DRAM credit stalls "
              "(read / write). Clock is GRBM_GUI_ACTIVE (summed over the 8 XCDs) / 8 / kernel-only time.", ""]
        cols = ["clean_cold", "clean_warm", "dirty_cold", "dirty_warm", "write_a", "sleep", "nothing"]
        rows = []
        for s in shapes:
            for v in M.VERSIONS:
                for m in cols:
                    r = pm.get((s, v, m))
                    if not r:
                        continue
                    hit = r["TCC_HIT_sum"] / (r["TCC_HIT_sum"] + r["TCC_MISS_sum"])
                    us = tr[(s, v, m)]["us"] if (s, v, m) in tr else float("nan")
                    rows.append([s, LABEL[v], m, f"{us:.1f}", f"{100 * hit:.1f}%",
                                 f"{r['TCC_EA0_RDREQ_sum'] / 1e6:.2f}M / {r['TCC_EA0_WRREQ_sum'] / 1e6:.2f}M",
                                 f"{r['TCC_EA0_RDREQ_DRAM_sum'] / 1e6:.2f}M / {r['TCC_EA0_WRREQ_DRAM_sum'] / 1e6:.2f}M",
                                 f"{r['TCC_ALL_TC_OP_WB_WRITEBACK_sum'] / 1e3:.1f}k",
                                 f"{r['TCC_NORMAL_WRITEBACK_sum'] / 1e3:.1f}k",
                                 f"{r['TCC_EA0_RDREQ_DRAM_CREDIT_STALL_sum'] / 1e6:.2f}M / "
                                 f"{r['TCC_EA0_WRREQ_DRAM_CREDIT_STALL_sum'] / 1e6:.2f}M",
                                 f"{r['GRBM_GUI_ACTIVE'] / 8 / us / 1e3:.2f} GHz"])
        L += table(["shape", "version", "mode", "us", "L2 hit", "L2 reads / writes", "DRAM reads / writes",
                    "op write-backs", "normal write-backs", "DRAM credit stalls", "clock"], rows)

        # Reads past L2 by mode.
        L += ["", "### Reads past L2 by mode (millions of requests)", "",
              "Capped's (and v13's) are the same in every mode; two-tile's move with the cache state.", ""]
        rows = []
        for s in shapes:
            for v in M.VERSIONS:
                rs = [pm.get((s, v, m)) for m in cols]
                rows.append([s, LABEL[v]] + [f"{r['TCC_EA0_RDREQ_sum'] / 1e6:.2f}" if r else "-" for r in rs]
                            + [f"{pm[(s, v, 'clean_cold')]['TCC_ALL_TC_OP_WB_WRITEBACK_sum'] / 1e3:.0f}k"
                               if (s, v, "clean_cold") in pm else "-"])
        L += table(["shape", "version"] + cols + ["op write-backs (clean_cold)"], rows)

        # Correlation of the per-mode time change with the reads past L2.
        L += ["", "### Time change against reads past L2", "",
              "For each small shape and policy: the extra reads past L2 of two-tile over capped (clean_cold), "
              "and each policy's slow-down from clean_cold to dirty_cold and speed-up to clean_warm.", ""]
        rows = []
        for s in SMALL:
            if (s, cap, "clean_cold") not in pm or (s, tt, "clean_cold") not in pm:
                continue
            rc, rt = pm[(s, cap, "clean_cold")]["TCC_EA0_RDREQ_sum"], pm[(s, tt, "clean_cold")]["TCC_EA0_RDREQ_sum"]
            cells = [s, f"{pct(rt, rc):+.0f}%"]
            for v in (cap, tt):
                d = pct(tr[(s, v, "dirty_cold")]["us"], tr[(s, v, "clean_cold")]["us"])
                w = pct(tr[(s, v, "clean_warm")]["us"], tr[(s, v, "clean_cold")]["us"])
                cells += [f"{d:+.1f}%", f"{w:+.1f}%"]
            rows.append(cells)
        L += table(["shape", "two-tile extra reads past L2", "capped: dirty", "capped: warm", "two-tile: dirty",
                    "two-tile: warm"], rows)

    # 6. Release timing and clocks.
    rel = load("release.jsonl")
    if rel:
        L += ["", "## 6. Two-tile's partial publish (s_memrealtime stamps)", "",
              "Medians over programs and launches, in us. head MAC: the head piece; store drain: from the end of "
              "the MAC to the partial stores completing; release: from there to the end of the head segment, "
              "i.e. the flag atomic and its completion (with buffer_wbl2 when the flag is a release); owner wait: "
              "the owner's spin for its peer's flag; tail: last stamp minus first "
              "start. \"relaxed\" is the timing-only control with a relaxed flag store (no buffer_wbl2). Each "
              "stamp adds a barrier, so phases are slightly longer than in the real kernel; \"kernel\" is the "
              "unpatched two-tile kernel's trace time in the same mode (section 2). wrong counts launches "
              "whose result did not match.", ""]
        rows = [[r["shape"], r["flag"], r["mode"], f"{r['head_mac']:.1f}", f"{r['store']:.1f}", f"{r['release']:.2f}",
                 f"{r['release_p90']:.2f}", f"{r['owner_mac']:.1f}", f"{r['owner_wait']:.1f}", f"{r['owner_fixup']:.1f}",
                 f"{r['tail']:.1f}",
                 f"{tr[(r['shape'], tt, r['mode'])]['us']:.1f}" if (r["shape"], tt, r["mode"]) in tr else "-",
                 r["wrong"]] for r in rel]
        L += table(["shape", "flag", "mode", "head MAC", "store drain", "release", "release p90", "owner MAC",
                    "owner wait", "owner fixup", "tail", "kernel", "wrong"], rows)
    clk = load("clocks.jsonl")
    if clk:
        L += ["", "## 7. Clock and power while each mode loops", "",
              "sysfs `freq1_input` (sclk) and `power1_input`, sampled about every 1 ms while the GEMM and the mode's "
              "work loop for about 2 s; median and 10th percentile of sclk, median power.", ""]
        rows = [[r["shape"], LABEL.get(r["version"], r["version"]), r["mode"], f"{r['sclk_med']:.0f}",
                 f"{r['sclk_p10']:.0f}", f"{r['power_med']:.0f}"] for r in clk]
        L += table(["shape", "version", "mode", "sclk median (MHz)", "sclk p10 (MHz)", "power median (W)"], rows)

    text = "\n".join(L) + "\n"
    with open(os.path.join(M.RESULTS, "modes.md"), "w") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
